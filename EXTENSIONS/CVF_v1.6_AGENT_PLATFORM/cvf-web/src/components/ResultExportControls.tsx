export type ExportLabels = { [Key in keyof (typeof exportLabels)['en']]: string };

interface ResultExportControlsProps {
    labels: ExportLabels;
    exportLang: ExportLanguage;
    onExportLangChange: (language: ExportLanguage) => void;
    copied: boolean;
    exporting: string | null;
    failures: Partial<Record<ExportFormat, boolean>>;
    showExportMenu: boolean;
    onToggleMenu: () => void;
    onCopy: () => void;
    onDownloadMarkdown: () => void;
    onExportPdf: () => void;
    onExportDocx: () => void;
    onDownloadPack: () => void;
}

export function ResultExportControls({
    labels, exportLang, onExportLangChange, copied, exporting, failures,
    showExportMenu, onToggleMenu, onCopy, onDownloadMarkdown, onExportPdf, onExportDocx, onDownloadPack,
}: ResultExportControlsProps) {
    return (
        <>
            <div className="relative">
                <button
                    onClick={onToggleMenu}
                    aria-expanded={showExportMenu}
                    className="px-4 py-2 border border-gray-300 dark:border-gray-600 rounded-lg hover:bg-gray-100 dark:hover:bg-gray-800 transition-colors"
                >
                    📄 Export
                </button>

                {showExportMenu && (
                    <div className="absolute right-0 mt-2 w-64 bg-white dark:bg-gray-800 rounded-lg shadow-lg border border-gray-200 dark:border-gray-700 z-10">
                        <div className="px-4 py-3 border-b border-gray-200 dark:border-gray-700">
                            <div className="text-sm font-medium text-gray-900 dark:text-white">{labels.helpTitle}</div>
                            <div className="text-xs text-gray-500 dark:text-gray-400 mt-1">{labels.helpDesc}</div>
                        </div>

                        <div className="px-4 py-2 border-b border-gray-200 dark:border-gray-700">
                            <div className="text-xs text-gray-500 mb-1">{labels.langLabel}:</div>
                            <div className="flex gap-2">
                                <button
                                    onClick={() => onExportLangChange('vi')}
                                    className={`px-3 py-1 text-xs rounded ${exportLang === 'vi'
                                        ? 'bg-blue-600 text-white'
                                        : 'bg-gray-100 dark:bg-gray-700 text-gray-700 dark:text-gray-300'
                                        }`}
                                >
                                    🇻🇳 Tiếng Việt
                                </button>
                                <button
                                    onClick={() => onExportLangChange('en')}
                                    className={`px-3 py-1 text-xs rounded ${exportLang === 'en'
                                        ? 'bg-blue-600 text-white'
                                        : 'bg-gray-100 dark:bg-gray-700 text-gray-700 dark:text-gray-300'
                                        }`}
                                >
                                    🇺🇸 English
                                </button>
                            </div>
                        </div>

                        <button
                            onClick={onCopy}
                            className="w-full px-4 py-3 text-left hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm"
                        >
                            {copied ? labels.copied : labels.copyBtn}
                        </button>
                        <button
                            onClick={onDownloadMarkdown}
                            className="w-full px-4 py-3 text-left hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm"
                        >
                            {labels.downloadBtn}
                        </button>
                        <button
                            onClick={onExportPdf}
                            disabled={exporting === 'pdf'}
                            aria-label={exporting === 'pdf' ? labels.exportingPdf : undefined}
                            className="w-full px-4 py-3 text-left hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm disabled:opacity-50"
                        >
                            {exporting === 'pdf' ? labels.exporting : labels.downloadPdf}
                        </button>
                        <button
                            onClick={onExportDocx}
                            disabled={exporting === 'docx'}
                            aria-label={exporting === 'docx' ? labels.exportingDocx : undefined}
                            className="w-full px-4 py-3 text-left hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm disabled:opacity-50"
                        >
                            {exporting === 'docx' ? labels.exporting : labels.downloadDocx}
                        </button>
                        <div className="border-t border-gray-200 dark:border-gray-700">
                            <button
                                onClick={onDownloadPack}
                                data-testid="download-pack-btn"
                                className="w-full px-4 py-3 text-left hover:bg-blue-50 dark:hover:bg-blue-900/20 rounded-b-lg flex items-center gap-2 text-sm text-blue-700 dark:text-blue-300"
                            >
                                📦 Download Deliverable Pack (.md)
                            </button>
                        </div>
                    </div>
                )}
            </div>

            {failures.pdf && (
                <div role="alert" data-testid="export-error-pdf" className="flex items-center gap-2 rounded-lg border border-red-300 bg-red-50 px-3 py-2 text-sm text-red-800 dark:border-red-700 dark:bg-red-900/20 dark:text-red-200">
                    <span>{labels.pdfError}</span>
                    <button type="button" onClick={onExportPdf} className="font-semibold underline underline-offset-2">
                        {labels.retryPdf}
                    </button>
                </div>
            )}
            {failures.docx && (
                <div role="alert" data-testid="export-error-docx" className="flex items-center gap-2 rounded-lg border border-red-300 bg-red-50 px-3 py-2 text-sm text-red-800 dark:border-red-700 dark:bg-red-900/20 dark:text-red-200">
                    <span>{labels.docxError}</span>
                    <button type="button" onClick={onExportDocx} className="font-semibold underline underline-offset-2">
                        {labels.retryDocx}
                    </button>
                </div>
            )}
        </>
    );
}
